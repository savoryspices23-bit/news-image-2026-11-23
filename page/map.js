function drawMap(stories, reg, w, h) {
  const LON0 = -170, LON1 = 180, LAT0 = 78, LAT1 = -50;
  const X = (lon) => ((lon - LON0) / (LON1 - LON0)) * w;
  const Y = (lat) => ((LAT0 - lat) / (LAT0 - LAT1)) * h;
  const poly = (pts, fill) => `<polygon points="${pts.map(([lo, la]) => `${X(lo).toFixed(1)},${Y(la).toFixed(1)}`).join(' ')}" fill="${fill}"/>`;
  let out = LAND.map((p) => poly(p, '#cbbf9f')).join('') + WATER.map((p) => poly(p, '#dfe8ee')).join('');
  // Small dots for the briefs first, so the numbered pins sit on top.
  stories.slice(13).forEach((s) => {
    out += `<circle cx="${X(s.lon).toFixed(1)}" cy="${Y(s.lat).toFixed(1)}" r="2.6" fill="${reg[s.r][1]}" stroke="#fff" stroke-width=".8"/>`;
  });
  stories.slice(0, 13).forEach((s, i) => {
    const x = X(s.lon), y = Y(s.lat);
    out += `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="6.2" fill="${reg[s.r][1]}" stroke="#fff" stroke-width="1"/>` +
      `<text x="${x.toFixed(1)}" y="${(y + 3).toFixed(1)}" text-anchor="middle" font-family="Arial" font-weight="700" font-size="8" fill="#fff">${i + 1}</text>`;
  });
  return `<svg width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" xmlns="http://www.w3.org/2000/svg">${out}</svg>`;
}
